# Job B: The Family Report

# Let's define a realistic dataset that matches the family report criteria (FLG, BRK, SHF) and tolerance range (24.95 - 25.05)
raw_lines = [
    "FLG-001, 25.00",
    "BRK-001, 24.98",
    "SHF-001, 25.02",
    "FLG-002, 24.90",  # Out of tolerance
    "BRK-002, 25.01",
    "SHF-002, 25.06",  # Out of tolerance
    "FLG-003, 25.04",
    "BRK-003, 24.96",
    "SHF-003, 24.99",
    "FLG-004, 25.00"
]

# Parse raw lines (Job A logic adjusted for the new dataset)
codes = []
dias = []
for line in raw_lines:
    code_part, dia_part = line.split(",")
    codes.append(code_part.strip().upper())
    dias.append(float(dia_part.strip()))

# 1. Collect measurements for each family (FLG, BRK, SHF)
families = ["FLG", "BRK", "SHF"]
family_data = {fam: [] for fam in families}

for i in range(len(codes)):
    code = codes[i]
    dia = dias[i]
    for fam in families:
        if code.startswith(fam):
            family_data[fam].append(dia)

# 2. Print report per family
print("=== FAMILY REPORT ===")
for fam in families:
    measurements = family_data[fam]
    count = len(measurements)
    if count > 0:
        mean_val = sum(measurements) / count
        min_val = min(measurements)
        max_val = max(measurements)
        spread = max_val - min_val
        print(f"Family {fam}: Count={count}, Mean={mean_val:.3f}, Min={min_val:.2f}, Max={max_val:.2f}, Spread={spread:.2f}")
    else:
        print(f"Family {fam}: No parts registered")

print("\n=== TOLERANCE CHECK ===")
# 3. Flag parts outside 24.95–25.05 range
out_of_tolerance_count = 0
total_parts = len(codes)

for i in range(len(dias)):
    if dias[i] < 24.95 or dias[i] > 25.05:
        print(f"OUT OF TOLERANCE: {codes[i]} ({dias[i]})")
        out_of_tolerance_count += 1

# 4. Finish with an overall summary line
acceptance_pct = ((total_parts - out_of_tolerance_count) / total_parts) * 100
print("\n=== OVERALL SUMMARY ===")
print(f"Total parts: {total_parts}")
print(f"Total out of tolerance: {out_of_tolerance_count}")
print(f"Acceptance rate: {acceptance_pct:.1f}%")

"""### Job C: The Backup Audit

We will perform two steps:
1. Create a true clone of `dias` using slicing (`dias[:]`), filter it for in-tolerance values, and verify the original remains unchanged.
2. Run the experiment using a direct assignment (alias) `backup = dias`, append `99.9` to the backup, and observe how it affects the original `dias` list.
"""

# Step 1: True Cloning with dias[:]
backup = dias[:]  # A clone, not an alias

# Build cleaned by looping and appending only in-tolerance values (24.95 to 25.05)
cleaned = []
for dia in dias:
    if 24.95 <= dia <= 25.05:
        cleaned.append(dia)

print("=== True Clone Step ===")
print("Length of original dias: ", len(dias))
print("Length of backup clone:  ", len(backup))
print("Length of cleaned list:  ", len(cleaned))
print("Original dias values:    ", dias)
print("Backup clone values:     ", backup)
print("Cleaned values:          ", cleaned)
print("Is dias unchanged?       ", dias == [25.0, 24.98, 25.02, 24.9, 25.01, 25.06, 25.04, 24.96, 24.99, 25.0])

# Step 2: The Alias Experiment
print("\n=== The Alias Experiment ===")
backup = dias  # Creates a reference (alias) instead of a clone
backup.append(99.9)

print("Modified backup list:    ", backup)
print("Resulting dias list:     ", dias)
print("Does dias contain 99.9?  ", 99.9 in dias)

# Restore the original state of dias for safety
dias.remove(99.9)
print("Original dias restored:  ", dias)